import { describe, expect, it } from 'vitest'
import { daysUntilEvent, ddayLabel } from '@/lib/format'

/**
 * **며칠 남았는가.**
 *
 * 목록에서 어느 행사가 급한지 보여 주는 숫자다. 하루라도 어긋나면
 * 연주회 전날에 「D-2」 가 떠서, 원장님이 하루를 더 있다고 믿으신다.
 * 서버는 대개 UTC 이고 학원은 한국이라 **자정 기준이 갈리기 쉬운 자리**다.
 */
const KST = (text: string) => new Date(text)

describe('daysUntilEvent', () => {
  it('같은 날이면 0', () => {
    expect(daysUntilEvent('2026-11-05T15:00:00+09:00', KST('2026-11-05T09:00:00+09:00'))).toBe(0)
  })

  it('다음 날이면 1', () => {
    expect(daysUntilEvent('2026-11-06T15:00:00+09:00', KST('2026-11-05T23:00:00+09:00'))).toBe(1)
  })

  it('지난 행사는 음수', () => {
    expect(daysUntilEvent('2026-11-01T15:00:00+09:00', KST('2026-11-05T09:00:00+09:00'))).toBe(-4)
  })

  it('시각이 아니라 **날**로 센다 — 몇 시간 뒤여도 오늘은 오늘', () => {
    // 오후 3시 연주회를 아침 9시에 보면 6시간 남았지만 「오늘」이다
    expect(ddayLabel('2026-11-05T15:00:00+09:00', KST('2026-11-05T09:00:00+09:00'))).toBe('오늘')
  })

  it('UTC 로 돌아가는 서버에서도 한국 날짜로 센다', () => {
    /*
     * **날짜 경계가 갈리는 자리**로 고른 예다.
     *
     *   지금   UTC 11월 4일 16:00  =  한국 11월 5일 새벽 1시
     *   연주회 UTC 11월 5일 06:00  =  한국 11월 5일 오후 3시
     *
     * 한국으로 세면 **둘 다 11월 5일 — 오늘(0)** 이다.
     * UTC 자정으로 세면 11월 4일과 11월 5일로 갈려 **하루가 더 남은 것(1)** 으로 보인다.
     * 연주회 당일 새벽에 켜신 원장님께 「내일입니다」라고 말하는 셈이다.
     *
     * 처음 쓴 예(한국 0시 30분 연주회)는 UTC 로 세도 답이 같아 **버그를 못 잡았다.**
     */
    expect(daysUntilEvent('2026-11-05T15:00:00+09:00', KST('2026-11-04T16:00:00Z'))).toBe(0)
  })

  it('말로 바꾸면 D- · 오늘 · 내일 · 지난 행사', () => {
    const now = KST('2026-11-05T09:00:00+09:00')
    expect(ddayLabel('2026-11-26T15:00:00+09:00', now)).toBe('D-21')
    expect(ddayLabel('2026-11-06T15:00:00+09:00', now)).toBe('내일')
    expect(ddayLabel('2026-11-05T15:00:00+09:00', now)).toBe('오늘')
    expect(ddayLabel('2026-10-05T15:00:00+09:00', now)).toBe('지난 행사')
  })
})
